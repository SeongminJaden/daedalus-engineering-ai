"""One record shape for a part, whether it came from CAD or from parameters.

A real STEP file and a parametric design rendered to CAD are different things
to produce and the same thing to analyse. Giving them one schema is what lets
a model trained on synthetic parts be evaluated on scraped ones, and what lets
the two be told apart afterwards, which matters more.

PROVENANCE AND LICENCE ARE REQUIRED
===================================
Not optional metadata to be filled in later. This project is Apache licensed
and public, so a part whose origin is unknown is a part that cannot be
published, and a dataset that lost track of which records those were is a
dataset that cannot be published either. A record without provenance cannot be
constructed at all, which is the only version of this rule that survives
contact with a bulk import.

The licence field is equally load bearing and equally unglamorous. "It was on
the internet" is not a licence, and a permissive set and a scraped set look
identical once both are JSON on disk.

VALIDITY DOMAIN
===============
Stated before implementing.

    This schema describes ONE part: a single solid body with its geometry,
    topology and whatever labels have been computed for it. An assembly is
    not a part, and mating conditions have no place to live here.

    Every physical quantity in a record is SIMULATED unless its own evidence
    field says otherwise. The schema carries the evidence level per label
    rather than per record, because a part may have a mass from exact geometry
    and a stress from a surrogate, and averaging those into one number for the
    record would destroy the distinction that matters.

    Geometry is recorded in SI, metres and kilograms, even though STEP files
    are conventionally in millimetres. The conversion happens at the analyzer
    boundary so that nothing downstream has to remember which unit it is in.
"""

from __future__ import annotations

from enum import Enum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, model_validator

#: Bumped whenever a stored record's meaning changes. A reader that finds a
#: version it does not know must refuse rather than guess, because a silently
#: misread dataset is worse than an absent one.
SCHEMA_VERSION = "0.1.0"


class ProvenanceKind(str, Enum):
    """Where a part came from. The distinction survives into the dataset."""

    #: Generated by this project from parameters, then rendered to CAD.
    SYNTHETIC_PARAMETRIC = "synthetic_parametric"
    #: A STEP file from a permissively licensed public dataset.
    PUBLIC_DATASET = "public_dataset"
    #: A STEP file belonging to the user. Local, never published.
    PROPRIETARY_LOCAL = "proprietary_local"
    #: Produced by a CAD tool driven by this project, such as Fusion.
    TOOL_ROUND_TRIP = "tool_round_trip"


class Licence(BaseModel):
    """The licence a part is available under, named rather than assumed."""

    model_config = ConfigDict(extra="forbid")

    identifier: str = Field(min_length=1)      # SPDX where one exists
    url: str = ""
    redistributable: bool
    notes: str = ""

    @model_validator(mode="after")
    def _unknown_is_not_redistributable(self) -> "Licence":
        vague = {"unknown", "unspecified", "none", "n/a", "tbd"}
        if self.identifier.strip().lower() in vague and self.redistributable:
            raise ValueError(
                f"licence {self.identifier!r} is not a licence, so the part "
                f"cannot be marked redistributable. An unnamed licence is the "
                f"one case where the safe default is no")
        return self


class Provenance(BaseModel):
    """Where the part came from, and whether it may be published."""

    model_config = ConfigDict(extra="forbid")

    kind: ProvenanceKind
    source: str = Field(min_length=1)          # url, dataset name, or generator
    licence: Licence
    generator: str = ""                        # for synthetic parts
    retrieved: str = ""                        # ISO date, for fetched parts

    @model_validator(mode="after")
    def _proprietary_is_never_redistributable(self) -> "Provenance":
        if (self.kind is ProvenanceKind.PROPRIETARY_LOCAL
                and self.licence.redistributable):
            raise ValueError(
                "a proprietary local part cannot be marked redistributable; "
                "that combination is how private CAD reaches a public repo")
        return self


class GeometrySummary(BaseModel):
    """Bulk geometric properties, in SI."""

    model_config = ConfigDict(extra="forbid")

    volume_m3: float = Field(gt=0.0)
    surface_area_m2: float = Field(gt=0.0)
    bounding_box_m: tuple[float, float, float]
    centre_of_mass_m: tuple[float, float, float]

    @model_validator(mode="after")
    def _fits_in_its_own_box(self) -> "GeometrySummary":
        box = self.bounding_box_m
        if min(box) <= 0.0:
            raise ValueError("a bounding box side must be positive")
        if self.volume_m3 > box[0] * box[1] * box[2] * (1.0 + 1e-9):
            raise ValueError(
                f"volume {self.volume_m3} exceeds its own bounding box, which "
                f"means the two were measured from different things")
        return self


class TopologySummary(BaseModel):
    """Counts from the B-rep. Cheap, and enough to catch a broken import."""

    model_config = ConfigDict(extra="forbid")

    solids: int = Field(ge=1)
    shells: int = Field(ge=1)
    faces: int = Field(ge=1)
    edges: int = Field(ge=0)
    vertices: int = Field(ge=0)


class PartRecord(BaseModel):
    """One part, as stored.

    `labels` holds computed physical quantities, each carrying its own
    evidence level, because a part may have an exact mass and a surrogate
    stress and the record must not blur them together.
    """

    model_config = ConfigDict(extra="forbid")

    schema_version: str = SCHEMA_VERSION
    part_id: str = Field(min_length=1)
    provenance: Provenance
    geometry: GeometrySummary
    topology: TopologySummary
    material_id: str = ""
    features: list[dict[str, Any]] = Field(default_factory=list)
    labels: dict[str, Any] = Field(default_factory=dict)
    notes: str = ""

    @model_validator(mode="after")
    def _version_is_the_one_we_write(self) -> "PartRecord":
        if self.schema_version != SCHEMA_VERSION:
            raise ValueError(
                f"record is schema {self.schema_version} and this code writes "
                f"{SCHEMA_VERSION}; refusing rather than guessing what the "
                f"fields meant then")
        return self

    @property
    def is_publishable(self) -> bool:
        """Whether this record may go into the public repository."""
        return (self.provenance.licence.redistributable
                and self.provenance.kind is not
                ProvenanceKind.PROPRIETARY_LOCAL)


def validate_record(payload: dict) -> PartRecord:
    """Parse a stored record, refusing anything that does not fit.

    Kept as a function rather than left to the caller so that every read path
    goes through the same door, including bulk imports, which are exactly
    where a malformed record would otherwise slip in unexamined.
    """
    return PartRecord.model_validate(payload)
